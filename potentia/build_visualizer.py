#!/usr/bin/env python3
"""Assemble the visualizer pages from visualizer/src/* and visualizer/core.js (stdlib only).

  visualizer/index.html                         local page, served by visualizer.py; uses the Python server when it answers,
                                                otherwise (or with ?js) the in-browser JavaScript core
  visualizer/potentia_visualizer_artifact.html  self-contained page for publishing as a claude.ai artifact (in-browser core only;
                                                no <html>/<head>/<body> tags, because the artifact host adds its own skeleton)
Edit the sources, not the generated files, then run:  python build_visualizer.py
"""
import os, re
V = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'visualizer')
rd = lambda p: open(os.path.join(V, p), encoding='utf-8').read()
head, body, app, core, luts = rd('src/head.html'), rd('src/body.html'), rd('src/app.js'), rd('core.js'), rd('src/luts.js')
# optional WebAssembly SIMD field kernel (assembled from src/field_simd.wat by src/build_wasm.js); without it the core uses its JavaScript loop
simd = rd('src/field_simd.wasm.js') if os.path.exists(os.path.join(V, 'src', 'field_simd.wasm.js')) else ''
if not simd:
    print('note: src/field_simd.wasm.js not found; building without the SIMD kernel')

def scripts(mode, target):
    return (f"<script>\nconst BUILD = {{ mode: '{mode}', target: '{target}' }};\n</script>\n"
            f"<script>\n{simd}{core}</script>\n<script>\n{luts}</script>\n<script>\n{app}</script>\n")

NOTE = '<!-- GENERATED by build_visualizer.py from visualizer/src and visualizer/core.js: edit those, not this file -->\n'
local = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
         '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' + NOTE + head + '</head>\n<body>\n' + body + scripts('auto', 'local') + '</body>\n</html>\n')
# downloads are blocked inside an artifact, so the artifact build drops the local page's file-download code
app_art = re.sub(r'/\*LOCAL_ONLY_BEGIN\*/.*?/\*LOCAL_ONLY_END\*/', '', app, flags=re.S)
artifact = NOTE + head + body + scripts('js', 'artifact').replace(app, app_art)
for name, text in (('index.html', local), ('potentia_visualizer_artifact.html', artifact)):
    open(os.path.join(V, name), 'w', encoding='utf-8').write(text)
    print(f'wrote visualizer/{name}  {len(text) / 1024:.0f} KB')
